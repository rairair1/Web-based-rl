#!/usr/bin/env python3
"""Generates a multi-player deployment: one isolated RuneLite container per
player behind Caddy, which serves https://<domain>/<player>/ with automatic
HTTPS certificates.

Usage:
    python3 deploy/setup.py play.kylemair.com

Reads deploy/players.txt (one name per line) and writes:
    deploy/compose.yml        the services
    deploy/Caddyfile          routing and HTTPS
    deploy/landing/index.html a page linking to each player
    deploy/.env               one generated password per player (kept on reruns)
"""

import argparse
import html
import re
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,30}$")
CADDY_IMAGE = "caddy:2.8.4"


def read_players(path):
    if not path.exists():
        sys.exit(f"Create {path} with one player name per line (see players.example.txt).")
    names = []
    for line in path.read_text().splitlines():
        name = line.split("#", 1)[0].strip().lower()
        if not name:
            continue
        if not NAME_RE.match(name):
            sys.exit(f"Invalid player name {name!r}: use lowercase letters, digits and dashes.")
        if name in names:
            sys.exit(f"Duplicate player name {name!r}.")
        names.append(name)
    if not names:
        sys.exit(f"{path} lists no players.")
    return names


def env_key(name):
    return "RLWEB_PASSWORD_" + name.upper().replace("-", "_")


def read_env(path):
    values = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                values[key.strip()] = value.strip()
    return values


def write_env(path, players, values):
    lines = ["# Web login passwords, one per player. Change one and rerun", "# `docker compose up -d` to sign that player out everywhere."]
    for name in players:
        key = env_key(name)
        if not values.get(key):
            values[key] = secrets.token_urlsafe(12)
        lines.append(f"{key}={values[key]}")
    path.write_text("\n".join(lines) + "\n")
    path.chmod(0o600)


def compose_yaml(players, memory):
    out = [
        "# Generated by deploy/setup.py. Edit players.txt and rerun it instead of editing this file.",
        "name: runelite-web",
        "",
        "services:",
        "  caddy:",
        f"    image: {CADDY_IMAGE}",
        "    ports:",
        '      - "80:80"',
        '      - "443:443"',
        '      - "443:443/udp"',
        "    volumes:",
        "      - ./Caddyfile:/etc/caddy/Caddyfile:ro",
        "      - ./landing:/srv/landing:ro",
        "      - caddy-data:/data",
        "      - caddy-config:/config",
        "    restart: unless-stopped",
    ]
    for name in players:
        out += [
            "",
            f"  rl-{name}:",
            "    build: ..",
            "    image: runelite-web:local",
            "    pull_policy: never",
            "    environment:",
            f"      RLWEB_PASSWORD: ${{{env_key(name)}:?run deploy/setup.py}}",
            f"      RLWEB_BASE_PATH: /{name}/",
            '      RLWEB_SECURE_COOKIE: "1"',
            "      RLWEB_GEOMETRY: 1280x720",
            "    volumes:",
            f"      - rl-{name}:/data",
            "    shm_size: 512m",
            f"    mem_limit: {memory}",
            "    restart: unless-stopped",
        ]
    out += ["", "volumes:", "  caddy-data:", "  caddy-config:"]
    out += [f"  rl-{name}:" for name in players]
    return "\n".join(out) + "\n"


def caddyfile(domain, players):
    out = [
        "# Generated by deploy/setup.py.",
        f"{domain} {{",
        "\theader Strict-Transport-Security \"max-age=31536000\"" if not domain.startswith("http://") else "",
    ]
    for name in players:
        out += [
            f"\tredir /{name} /{name}/",
            f"\thandle_path /{name}/* {{",
            f"\t\treverse_proxy rl-{name}:8080",
            "\t}",
        ]
    out += ["\thandle {", "\t\troot * /srv/landing", "\t\tfile_server", "\t}", "}"]
    return "\n".join(line for line in out if line) + "\n"


def landing_html(players):
    links = "\n".join(f'        <li><a href="{html.escape(n)}/">{html.escape(n)}</a></li>' for n in players)
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="robots" content="noindex" />
    <title>RuneLite Web</title>
    <style>
      :root {{ color-scheme: dark; }}
      body {{ margin: 0; min-height: 100dvh; display: grid; place-items: center; background: #111; color: #eee;
        font: 17px/1.4 system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif; }}
      main {{ width: min(360px, calc(100vw - 32px)); }}
      ul {{ list-style: none; padding: 0; display: grid; gap: 10px; }}
      a {{ display: block; padding: 14px 16px; border-radius: 10px; background: #222; border: 1px solid #333;
        color: #ff9b2f; text-decoration: none; font-weight: 600; }}
    </style>
  </head>
  <body>
    <main>
      <h1>RuneLite Web</h1>
      <p>Pick your name. Each player has their own RuneLite and password.</p>
      <ul>
{links}
      </ul>
    </main>
  </body>
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("domain", help="e.g. play.kylemair.com (or http://localhost:8088 to test without HTTPS)")
    parser.add_argument("--memory", default="2g", help="memory limit per player container (default 2g)")
    args = parser.parse_args()

    players = read_players(HERE / "players.txt")
    env_path = HERE / ".env"
    values = read_env(env_path)
    write_env(env_path, players, values)
    (HERE / "compose.yml").write_text(compose_yaml(players, args.memory))
    (HERE / "Caddyfile").write_text(caddyfile(args.domain, players))
    (HERE / "landing").mkdir(exist_ok=True)
    (HERE / "landing" / "index.html").write_text(landing_html(players))

    base = args.domain if args.domain.startswith("http") else f"https://{args.domain}"
    print(f"Generated deployment for {len(players)} player(s). Send each player their own link and password:\n")
    for name in players:
        print(f"  {base}/{name}/   password: {values[env_key(name)]}")
    print("\nStart or update with:  docker compose -f deploy/compose.yml up -d --build")


if __name__ == "__main__":
    main()
